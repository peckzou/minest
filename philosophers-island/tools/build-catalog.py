#!/usr/bin/env python3
"""Builds the great library's catalogue (library/catalog.js) from tools/catalog-list.py: a real cover for every book
(Open Library), and the full text of those in the public domain (Project Gutenberg), all saved locally.
Run from the project root:  python3 tools/build-catalog.py     (needs the network; re-runs are cached)"""
import json, os, re, sys, time, unicodedata, urllib.parse, urllib.request
exec(open('tools/catalog-list.py', encoding='utf-8').read())
UA = 'PhilosophersIsland/1.0 (local educational project)'
def fold(t): return ''.join(c for c in unicodedata.normalize('NFD', t or '') if unicodedata.category(c) != 'Mn').lower()
def get(url, binary=False, tries=2, timeout=40):
    for i in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=timeout) as r:
                d = r.read(); return d if binary else d.decode('utf-8', 'replace')
        except Exception as e: time.sleep(1.2 * (i + 1))
    return None
def pg_text(n):
    path = 'books-cache/pg%d.txt' % n
    if os.path.exists(path): return open(path, encoding='utf-8', errors='replace').read()
    s = str(n); d = '/'.join(s[:-1]) if len(s) > 1 else '0'; base = 'https://gutenberg.pglaf.org/%s/%s/%s' % (d, s, s)
    for suf, enc in (('-0.txt', 'utf-8'), ('.txt', 'latin-1'), ('-8.txt', 'latin-1')):
        d2 = get(base + suf, True, tries=1)
        if d2 and len(d2) > 3000 and b'<html' not in d2[:300].lower():
            t = d2.decode(enc, 'replace'); open(path, 'w', encoding='utf-8').write(t); return t
    return None
def cover(key, urls):
    path = 'library/covers/%s.jpg' % key
    if os.path.exists(path) and os.path.getsize(path) > 2500: return path
    for u in urls:
        d = get(u, True)
        if d and len(d) > 2500 and (d[:3] == b'\xff\xd8\xff' or d[:4] == b'\x89PNG'): open(path, 'wb').write(d); return path
    return None
def ol(title, author):
    cache = '/tmp/olc_%s.json' % re.sub(r'\W+', '_', fold(title + ' ' + author))[:80]
    if os.path.exists(cache): return json.load(open(cache))
    t = get('https://openlibrary.org/search.json?title=' + urllib.parse.quote(title) + '&author=' + urllib.parse.quote(author) + '&fields=key,title,cover_i,first_publish_year,edition_count&limit=8&sort=editions')
    d = json.loads(t) if t else {'docs': []}; json.dump(d, open(cache, 'w')); time.sleep(0.5); return d
os.makedirs('library/covers', exist_ok=True); os.makedirs('books-cache', exist_ok=True)
exec(open('tools/hall-list.py', encoding='utf-8').read())
def entry(key, zh, en, author, pg):
    file, kind, src, url = None, 'biblio', '仍在版权期或没有公版文字 · 只有书目', ''
    if str(pg).startswith('ws:'):
        path = 'books-cache/ws_%s.txt' % pg[3:]
        if os.path.exists(path): file, kind, src, url = path, 'ws', '维基文库（简体）', 'https://zh.wikisource.org/wiki/' + urllib.parse.quote(en)
        pg = 0
    pg = int(pg or 0)
    if pg:
        t = pg_text(pg); head = fold(t[:9000]) if t else ''
        words = [w for w in re.split(r'[^a-z0-9\u4e00-\u9fff]+', fold(en)) if len(w) > 3 or '\u4e00' <= w[:1] <= '\u9fff'][:3]
        ok = t and len(t) > 15000 and (fold(author.split()[-1]) in head or author in t[:9000] or (words and any(w in head for w in words)))
        if ok: file, kind, src, url = 'books-cache/pg%d.txt' % pg, 'pg', 'Project Gutenberg #%d' % pg, 'https://www.gutenberg.org/ebooks/%d' % pg
        else: print('   pg rejected:', zh, pg, flush=True)
    docs = [d for d in ol(en, author).get('docs', []) if d.get('cover_i')] if kind != 'ws' else []
    urls = ['https://covers.openlibrary.org/b/id/%d-M.jpg' % d['cover_i'] for d in docs[:2]] + (['https://gutenberg.pglaf.org/cache/epub/%d/pg%d.cover.medium.jpg' % (pg, pg)] if pg else [])
    c = cover(key, urls) if urls else None
    if not url and docs: url = 'https://openlibrary.org' + docs[0]['key']
    return {'key': key, 'zh': zh, 'title': en, 'author': author, 'cover': c, 'file': file, 'kind': kind, 'src': src, 'url': url}
out, n = [], 0
for cat, block in CATALOG.items():
    for line in block.strip().split('\n'):
        zh, en, author, pg, flags = (line.split('|') + [''])[:5]; n += 1
        b = entry('c%03d' % n, zh, en, author, pg); b['cat'] = cat; b['world'] = 'w' in flags; out.append(b)
        print('%-6s %-22s %s %s' % (cat, zh[:22], 'TEXT' if b['file'] else '----', 'cover' if b['cover'] else 'NOCOVER'), flush=True)
open('library/catalog.js', 'w', encoding='utf-8').write('/* generated by tools/build-catalog.py — the great library on the Island of Time */\nwindow.PICATALOG = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')
print('catalogue:', len(out), 'books,', sum(1 for b in out if b['file']), 'with text,', sum(1 for b in out if b['cover']), 'with covers,', sum(1 for b in out if b['world']), 'on the world wall')
LIB = {}
for hall, block in HALLS.items():
    LIB[hall] = []
    for k, line in enumerate(block.strip().split('\n')):
        zh, en, author, pg, azh = (line.split('|') + [''])[:5]; b = entry('h_%s_%d' % (hall, k + 1), zh, en, author, pg); b['authorZh'] = azh; LIB[hall].append(b)
    print('%-26s %d books, %d with text, %d covers' % (hall, len(LIB[hall]), sum(1 for b in LIB[hall] if b['file']), sum(1 for b in LIB[hall] if b['cover'])), flush=True)
open('library/books.js', 'w', encoding='utf-8').write('/* generated by tools/build-catalog.py — the halls\' own bookshelves */\nwindow.PILIB = ' + json.dumps(LIB, ensure_ascii=False, indent=0) + ';\n')
n2 = sum(len(v) for v in LIB.values()); print('halls:', n2, 'books,', sum(1 for v in LIB.values() for b in v if b['file']), 'with text,', sum(1 for v in LIB.values() for b in v if b['cover']), 'with covers')

#!/usr/bin/env node
/* Rebuilds sim-quotes.js entries from the 2D models' own step ↔ quotation tables.
   Usage (from the island's root):  node holo-lab-2/gen-quotes.js plato_forms lab:aristotle_mean …
   A plain key reads philosophy/models/minest_<key>.html (const MAP); lab:<key> reads the model from lab.min.js. */
const fs = require('fs'), dir = 'philosophy/models/';
const out = {}, info = {};
function match(s, i) { let d = 0, q = null; for (let j = i; j < s.length; j++) { const c = s[j]; if (q) { if (c === '\\') j++; else if (c === q) q = null; continue; } if (c === '"' || c === "'" || c === '`') q = c; else if (c === '[' || c === '{') d++; else if (c === ']' || c === '}') { d--; if (!d) return j + 1; } } return -1; }
for (const arg of process.argv.slice(2)) {
  if (arg.startsWith('lab:')) {
    const key = arg.slice(4), s = fs.readFileSync(dir + 'lab.min.js', 'utf8');
    const i = s.indexOf('slug:"minest_' + key + '"'), a = s.lastIndexOf('{id:', i), o = Function('return ' + s.slice(a, match(s, a)))();
    out[key] = o.stages.map((st) => st.mappings); info[key] = { core: o.coreQuestion, bound: o.boundaryNote, stages: o.stages.map((st) => { const c = Object.assign({}, st); delete c.mappings; return c; }) };
    continue;
  }
  const key = arg, s = fs.readFileSync(dir + 'minest_' + key + '.html', 'utf8');
  const i = s.indexOf('const MAP='), j = match(s, s.indexOf('{', i));
  const pre = (s.slice(s.indexOf('<script>') + 8, i).match(/(?:^|[;\n])\s*const ((?:[A-Z][A-Za-z0-9_]*=(?:'[^'\n]*'|"[^"\n]*"),?)+);/g) || []).map((l) => l.replace(/^[;\n\s]*/, '')).join('\n');
  const M = Function(pre + '\nreturn ' + s.slice(s.indexOf('{', i), j))();
  out[key] = Object.keys(M).sort().map((k) => M[k]);
  const t = /const TITLE=(\{[^\n]*\});/.exec(s); info[key] = { stages: t ? Object.values(Function('return ' + t[1])()) : [] };
}
let prev = {};
try { prev = Function('var HL={};' + fs.readFileSync('holo-lab-2/sim-quotes.js', 'utf8').replace(/window\.HL/g, 'HL') + ';return HL.simQ')(); } catch (e) {}
Object.assign(prev, out);
fs.writeFileSync('holo-lab-2/sim-quotes.js', "/* Generated by gen-quotes.js from philosophy/models (each model's own step ↔ quotation table), one entry per rebuilt 3D model. */\nwindow.HL && (window.HL.simQ = " + JSON.stringify(prev) + ");\n");
for (const k in out) { console.log('==', k, JSON.stringify(info[k])); out[k].forEach((st, i) => { console.log(' S' + (i + 1)); st.forEach((r, n) => console.log('   ' + n + ' ' + r[0] + '  〔' + r[3] + '〕')); }); }

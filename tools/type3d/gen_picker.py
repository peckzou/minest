#!/usr/bin/env python3
"""3D Type world picker (2026-11-13): writes type3d/picker.js — one panel listing every 3D typing world: the classic
3D Type pages (type3d/*.html) and the Typing Worlds worlds (typing-worlds/, read from the app's registry.ts, so a new
world shows up after re-running this). Each 3D Type page and the Typing Worlds page load picker.js; it replaces their
own world links / gallery with the one panel. Typing Worlds opens a world directly with ?world=<id>. Idempotent."""
import json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[2]
REG = (ROOT / 'tools/typing-worlds-app/src/engine/registry.ts').read_text(encoding='utf-8')

series = [dict(id=m[0], zh=m[1], en=m[2]) for m in re.findall(r"\{ id: '([a-z-]+)', label: '([^']+)', en: '([^']+)' \}", REG.split('export const WORLDS')[0])]
worlds = []
for blk in re.split(r"\n  \{\n", REG.split('export const WORLDS')[1])[1:]:
    def f(k, pat=r"'([^']*)'"):
        m = re.search(r"\n    " + k + r": " + pat, '\n' + blk); return m.group(1) if m else None
    wid = f('id')
    if not wid: continue
    worlds.append(dict(id=wid, n=int(f('number', r"(\d+)") or 0), en=f('name'), zh=f('nameZh'), series=f('series'),
                       poster=f('poster'), accent=f('accent')))
worlds.sort(key=lambda w: w['n'])
assert len(worlds) >= 20, len(worlds)

CLASSIC = [
    dict(page='index.html', en='Filament', zh='立体打印', poster='linear-gradient(160deg,#1b1f24,#3a4048 60%,#c9ced4)'),
    dict(page='firework.html', en='Firework', zh='烟花', poster='linear-gradient(160deg,#0b0d2a,#3a1d5a 60%,#ff7a3d)'),
    dict(page='topiary.html', en='Topiary', zh='园艺修剪', poster='linear-gradient(160deg,#20381f,#4f7a3a 60%,#cfe3a0)'),
    dict(page='saber.html', en='Saber', zh='光剑', poster='linear-gradient(160deg,#05060c,#14203a 60%,#4fd2ff)'),
    dict(page='quill.html', en='Quill', zh='羽毛笔', poster='linear-gradient(160deg,#2a1d12,#6a4a2a 60%,#f0dcb0)'),
    dict(page='neon.html', en='Neon', zh='霓虹', poster='linear-gradient(160deg,#120814,#3a1030 60%,#ff4a1c)'),
    dict(page='book.html', en='Book', zh='立体书', poster='linear-gradient(160deg,#2a1f18,#7a5a3a 60%,#f3e6c8)'),
    dict(page='workshop.html', en='Type Workshop', zh='文字工坊', poster='linear-gradient(160deg,#2a1a10,#7a4a26 60%,#ffb066)'),
]
DATA = json.dumps(dict(classic=CLASSIC, series=series, worlds=worlds), ensure_ascii=False, separators=(',', ':'))

JS = r'''/* 3D Type · world picker — generated by tools/type3d/gen_picker.py (do not edit by hand; edit the generator).
   One panel for every 3D typing world: the classic 3D Type pages and the Typing Worlds worlds. Loaded by type3d/*.html
   (it takes the place of their "Filament / Firework / …" links) and by typing-worlds/index.html (it takes the place of
   the 🌌 gallery). ?pick=1 opens it at start. */
(function () {
  if (window.T3DPicker) return;
  var D = @@DATA@@;
  var me = document.currentScript && document.currentScript.src || location.href;
  var BASE = new URL('../', me).href;                                   // the site root (type3d/ and typing-worlds/ sit side by side)
  var path = location.pathname, inTW = /\/typing-worlds\//.test(path), page = path.split('/').pop() || 'index.html';
  var curTW = null; try { curTW = new URLSearchParams(location.search).get('world'); } catch (e) {}
  function twNow() { var t = document.querySelector('.tw-world-name'); var name = t && t.textContent.trim(); var w = D.worlds.filter(function (x) { return x.zh === name || x.id === curTW; })[0]; return w ? w.id : curTW; }
  function urlOf(it) { return it.page ? BASE + 'type3d/' + it.page : BASE + 'typing-worlds/index.html?world=' + encodeURIComponent(it.id); }
  function esc(s) { return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
  var css = '#t3dp{position:fixed;inset:0;z-index:2147483000;background:rgba(6,7,12,.94);-webkit-backdrop-filter:blur(10px);backdrop-filter:blur(10px);color:#eef0f6;font:14px/1.4 -apple-system,BlinkMacSystemFont,"PingFang SC",sans-serif;overflow:auto;-webkit-overflow-scrolling:touch;padding:calc(env(safe-area-inset-top,0px) + 18px) 16px calc(env(safe-area-inset-bottom,0px) + 90px)}' +
    '#t3dp[hidden]{display:none}#t3dp h2{margin:0 0 2px;font-size:20px;font-weight:700}#t3dp .sub{opacity:.6;font-size:12px;margin-bottom:14px}' +
    '#t3dp h3{margin:18px 0 8px;font-size:13px;font-weight:600;letter-spacing:.06em;opacity:.75}' +
    '#t3dp .g{display:grid;grid-template-columns:repeat(auto-fill,minmax(132px,1fr));gap:10px}' +
    '#t3dp a{display:flex;flex-direction:column;justify-content:flex-end;min-height:84px;padding:10px 11px;border-radius:14px;text-decoration:none;color:#fff;position:relative;overflow:hidden;box-shadow:inset 0 0 0 1px rgba(255,255,255,.12)}' +
    '#t3dp a::before{content:"";position:absolute;inset:0;background:linear-gradient(180deg,rgba(0,0,0,0) 30%,rgba(0,0,0,.55));}' +
    '#t3dp a b,#t3dp a span,#t3dp a i{position:relative}#t3dp a b{font-size:15px;font-weight:700;text-shadow:0 1px 3px rgba(0,0,0,.5)}#t3dp a span{font-size:11px;opacity:.85}' +
    '#t3dp a i{position:absolute;left:10px;top:8px;font-style:normal;font-size:11px;opacity:.8}#t3dp a.on{box-shadow:inset 0 0 0 2px #fff,0 0 0 2px rgba(255,255,255,.25)}' +
    '#t3dp .x{position:fixed;right:calc(env(safe-area-inset-right,0px) + 14px);top:calc(env(safe-area-inset-top,0px) + 12px);width:38px;height:38px;border-radius:50%;border:0;background:rgba(255,255,255,.14);color:#fff;font-size:18px;cursor:pointer}' +
    '.t3dp-btn{font:600 12px/1 -apple-system,sans-serif;color:#fff;background:rgba(255,255,255,.14);border:1px solid rgba(255,255,255,.25);border-radius:999px;padding:6px 11px;cursor:pointer;-webkit-backdrop-filter:blur(8px);backdrop-filter:blur(8px);pointer-events:auto}';
  var panel = null;
  function build() {
    var st = document.createElement('style'); st.textContent = css; document.head.appendChild(st);
    panel = document.createElement('div'); panel.id = 't3dp'; panel.hidden = true; panel.setAttribute('role', 'dialog'); panel.setAttribute('aria-label', '3D Type · 选择世界');
    var cur = inTW ? twNow() : page;
    var card = function (it, num) {
      var on = it.page ? (!inTW && it.page === page) : (inTW && it.id === cur);
      return '<a href="' + esc(urlOf(it)) + '" class="' + (on ? 'on' : '') + '" style="background:' + esc(it.poster || '#333') + '">' + (num ? '<i>' + num + '</i>' : '') + '<b>' + esc(it.zh) + '</b><span>' + esc(it.en) + '</span></a>';
    };
    var h = '<button type="button" class="x" aria-label="关闭">×</button><h2>3D Type · 立体打字</h2><div class="sub">' + (D.classic.length + D.worlds.length) + ' 个 3D 打字世界 · 点一个进入</div>';
    h += '<h3>经典 3D TYPE</h3><div class="g">' + D.classic.map(function (c) { return card(c); }).join('') + '</div>';
    D.series.forEach(function (s) {
      var ws = D.worlds.filter(function (w) { return w.series === s.id; }); if (!ws.length) return;
      h += '<h3>' + esc(s.zh) + ' · ' + esc(s.en.toUpperCase()) + '</h3><div class="g">' + ws.map(function (w) { return card(w, String(w.n).padStart(2, '0')); }).join('') + '</div>';
    });
    var rest = D.worlds.filter(function (w) { return !D.series.some(function (s) { return s.id === w.series; }); });
    if (rest.length) h += '<h3>更多</h3><div class="g">' + rest.map(function (w) { return card(w, String(w.n).padStart(2, '0')); }).join('') + '</div>';
    panel.innerHTML = h; document.body.appendChild(panel);
    panel.querySelector('.x').onclick = close;
    panel.addEventListener('click', function (e) { var a = e.target.closest('a'); if (!a) return; e.preventDefault(); location.href = a.href; });
    ['keydown', 'keyup', 'keypress'].forEach(function (t) { window.addEventListener(t, function (e) { if (!panel.hidden) { if (t === 'keydown' && e.key === 'Escape') close(); e.stopImmediatePropagation(); } }, true); });
  }
  function open() { if (!panel) build(); panel.hidden = false; var on = panel.querySelector('a.on'); if (on && on.scrollIntoView) on.scrollIntoView({ block: 'center' }); }
  function close() { if (panel) panel.hidden = true; }
  function mount() {
    if (inTW) {                                                         // Typing Worlds: the 🌌 button opens this panel instead of its own gallery
      var hook = function () { var g = document.querySelector('.tw-gallery-trigger'); if (!g || g.__t3d) return !!g; g.__t3d = 1;
        g.addEventListener('click', function (e) { e.preventDefault(); e.stopImmediatePropagation(); open(); }, true); g.title = '3D Type · 选择世界'; return true; };
      if (!hook()) { var n = 0, iv = setInterval(function () { if (hook() || ++n > 80) clearInterval(iv); }, 150); }
    } else {                                                            // a 3D Type page: its "A / B / C" links become one button
      var t = document.getElementById('title');
      if (t) {
        [].slice.call(t.querySelectorAll('a')).forEach(function (a) { a.remove(); });
        [].slice.call(t.childNodes).forEach(function (n) { if (n.nodeType === 3 && /^[\s/]*$/.test(n.textContent)) n.remove(); });
        var b = document.createElement('button'); b.type = 'button'; b.className = 't3dp-btn'; b.textContent = '▾ 切换世界'; b.style.marginLeft = '10px';
        b.addEventListener('click', function (e) { e.stopPropagation(); open(); }); t.appendChild(b); t.style.pointerEvents = 'auto';
      }
    }
    try { if (new URLSearchParams(location.search).get('pick') === '1') open(); } catch (e) {}
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', mount); else mount();
  window.T3DPicker = { open: open, close: close, data: D };
})();
'''
(ROOT / 'type3d/picker.js').write_text(JS.replace('@@DATA@@', DATA), encoding='utf-8')
print('picker.js:', len(CLASSIC), 'classic +', len(worlds), 'Typing Worlds in', len(series), 'series')

# every classic page loads it (the workshop has its own top bar and is left as it is)
for c in CLASSIC[:-1]:
    p = ROOT / 'type3d' / c['page']; s = p.read_text(encoding='utf-8')
    if 'picker.js' in s: continue
    i = s.rfind('</body>'); s = s[:i] + '<script src="picker.js"></script>\n' + s[i:]; p.write_text(s, encoding='utf-8'); print('  +', c['page'])

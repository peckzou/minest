"""rail-common.js = the shared half of Knowledge Drive (data through a provider, card info, billboard art, the board's back,
low-poly kit, landscapes), cut from ../knowledge-drive/drive.js so Train and Metro reuse it without changing the drive.
Re-run after drive.js changes."""
from pathlib import Path
HERE = Path(__file__).resolve().parent
src = (HERE.parent / 'knowledge-drive' / 'drive.js').read_text(encoding='utf-8')
a = src.index("  if (window.MinestDrive && window.MinestDrive.version) return;\n"); a = src.index('\n', a) + 1
b = src.index("  // ---------------------------------------------------------------- the drive")
body = src[a:b]
out = ("/* GENERATED by build_common.py from knowledge-drive/drive.js — do not edit here. */\n"
       "window.KRail = (function () {\n  'use strict';\n" + body +
       "  return { hash: hash, rng: rng, clamp: clamp, lerp: lerp, ease: ease, esc: esc, defaultProvider: defaultProvider, findCard: findCard, info: info, plan: plan,\n"
       "    STYLES: STYLES, styleById: styleById, kit: kit, loadImg: loadImg, drawBoard: drawBoard, drawBack: drawBack, signTex: signTex, wrap: wrap, rr: rr, shade: shade, plain: plain, FONT: FONT, PAL: PAL };\n})();\n")
(HERE / 'rail-common.js').write_text(out, encoding='utf-8')
print('rail-common.js', len(out))

"""My World 71 — one shell for every voxel world: the third-party engine worlds (Bibury, Downton, Neuschwanstein,
Hallstatt, Venice) run with Santorini's console instead of their own intro hints, hotbar, touch buttons and joystick.

Built from Codex's own modules, not a copy of them: ui/world-editor-camera.js, ui/world-navigation.js and
ui/my-world-controls.css are taken as they are, with the few Santorini names swapped for the engine page's
(__santorini → __voxel, #oia-gl → #gl, #oia-mm → #mm, #oia-title → #title …), plus tools/myworld/voxel-shell/console.js
(the console: Walk in / 视角 / 地图 / 地点, 一键世界 / 体素世界 / 返回小岛) and extra.css → ui/voxel-shell.js / .css.

Each engine's app.js gets what Codex gave Santorini's engine: consoleControls (input / stop) used by movePlayer, the
editing-camera hook at the top of updateCamera, daylight while editing, and window.__voxel = its global with controls.
Its page loads ../ui/voxel-shell.css / .js. My World's pages get tools/myworld/voxel-shell/parent.js (mn-world-shell-71):
those worlds open straight into the engine page, and the console's messages reach My World.
Safe to re-run."""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SRC = HERE / 'voxel-shell'
WORLDS = [  # id, page, app.js, global, name
    ('bibury', 'bibury/bibury.html', 'bibury/bb-world/app.js', '__bb', '拜伯里'),
    ('downton', 'downton/downton.html', 'downton/da-world/app.js', '__da', '唐顿庄园'),
    ('neuschwanstein', 'neuschwanstein/neuschwanstein.html', 'neuschwanstein/ns-world/app.js', '__ns', '新天鹅堡'),
    ('hallstatt', 'hallstatt/hallstatt.html', 'hallstatt/hallstatt-world/app.js', '__hallstatt', '哈尔施塔特'),
    ('venice', 'venice.html', 'venice-world/app.js', '__venice', '威尼斯'),
]
PROXY = [  # page, kind, id, name, title — worlds on their own engines (proxy.js)
    ('hobbiton.html', 'hobbiton', 'hobbiton', '霍比屯', 'HOBBITON 霍比屯'),
    ('giethoorn/index.html', 'react', 'giethoorn', '羊角村', 'GIETHOORN 羊角村'),
    ('lauterbrunnen/index.html', 'react', 'lauterbrunnen', '劳特布龙嫩', 'LAUTERBRUNNEN 劳特布龙嫩'),
]
MY_WORLD = ['iPhoneDuo.html', 'iPhoneDuo69.html', 'iphone.html', 'iPhone53.8241.html', 'index.html', 'ipad.html',
            'ios/Minest/Minest/iPhoneDuo.html', 'ios/Minest/Minest/index.html', 'ios/Minest/Minest/ipad.html',
            'ios/Minest/Minest/iphone.html', 'ios/Minest/Minest/iphone18.0.html']

# ---- 1. the shell bundle, from Codex's modules
engine_ids = set()
for w in WORLDS:
    engine_ids |= set(re.findall(r'id="([A-Za-z0-9]+)"', (ROOT / w[1]).read_text(encoding='utf-8')))
css = (ROOT / 'ui/my-world-controls.css').read_text(encoding='utf-8')
css = re.sub(r'#oia-([A-Za-z0-9]+)(?![\w-])', lambda m: '#' + m.group(1) if m.group(1) in engine_ids else m.group(0), css)
(ROOT / 'ui/voxel-shell.css').write_text('/* generated by tools/myworld/build_world_shells.py from ui/my-world-controls.css (Codex) — do not edit */\n'
                                         + css + '\n' + (SRC / 'extra.css').read_text(encoding='utf-8'), encoding='utf-8')

cam = (ROOT / 'ui/world-editor-camera.js').read_text(encoding='utf-8')
for a, b in [("function scene(){return root.__santorini;}", "function scene(){var s=root.__voxel;if(s&&s.world&&!s.world.buildings)s.world.buildings=[];return s;}"),
             ("getElementById('oia-gl')", "getElementById('gl')"), ("e.target.id==='oia-gl'", "e.target.id==='gl'"),
             ("getElementById('oia-modeLabel')", "getElementById('modeLabel')"), ("e.target.id==='oia-mm'", "e.target.id==='mm'")]:
    assert a in cam, a
    cam = cam.replace(a, b)
assert 'oia-gl' not in cam and cam.count('__santorini') == 1   # left: ensureContext, which needs My World and returns at once here
nav = (ROOT / 'ui/world-navigation.js').read_text(encoding='utf-8')
assert nav.count('root.__santorini') == 2
nav = nav.replace('root.__santorini', 'root.__voxel')
js = ('/* generated by tools/myworld/build_world_shells.py — Codex\'s ui/world-editor-camera.js and ui/world-navigation.js for an engine page, and the console — do not edit */\n'
      + cam + '\n' + nav + '\n' + (SRC / 'run.js').read_text(encoding='utf-8') + '\n' + (SRC / 'console.js').read_text(encoding='utf-8'))
(ROOT / 'ui/voxel-shell.js').write_text(js, encoding='utf-8')
(ROOT / 'ui/voxel-shell-lite.js').write_text('/* generated by tools/myworld/build_world_shells.py — proxy.js, Codex\'s ui/world-navigation.js and the console, for worlds on their own engines — do not edit */\n'
                                              + (SRC / 'proxy.js').read_text(encoding='utf-8') + '\n' + nav + '\n' + (SRC / 'console.js').read_text(encoding='utf-8'), encoding='utf-8')

# ---- 2. each engine: what Codex gave Santorini's
MOVE = [
    ("    const p = player;\n    const fwd = (keys.KeyW || keys.ArrowUp ? 1 : 0) - (keys.KeyS || keys.ArrowDown ? 1 : 0) - joy.y;\n    const side = (keys.KeyD || keys.ArrowRight ? 1 : 0) - (keys.KeyA || keys.ArrowLeft ? 1 : 0) + joy.x;",
     "    const p = player, n = consoleInput;\n    p.yaw += ((n.lookLeft ? 1 : 0) - (n.lookRight ? 1 : 0) - (n.lookX || 0)) * dt * 1.6;\n    p.pitch = Math.max(-1.5, Math.min(1.5, p.pitch + ((n.lookUp ? 1 : 0) - (n.lookDown ? 1 : 0) + (n.lookY || 0)) * dt * 1.2));\n"
     "    const fwd = (keys.KeyW || keys.ArrowUp || n.forward ? 1 : 0) - (keys.KeyS || keys.ArrowDown || n.back ? 1 : 0) - joy.y + (n.moveY || 0);\n    const side = (keys.KeyD || keys.ArrowRight || n.right ? 1 : 0) - (keys.KeyA || keys.ArrowLeft || n.left ? 1 : 0) + joy.x + (n.moveX || 0);"),
    ("    const sprint = !!(keys.ShiftLeft || keys.ShiftRight || keys.ControlLeft && !p.fly);\n    const jump = !!(keys.Space || touchBtn.jump);\n    const down = !!(keys.KeyC || (p.fly && (keys.ShiftLeft || keys.ShiftRight)) || touchBtn.down);",
     "    const sprint = !!(n.fast || keys.ShiftLeft || keys.ShiftRight || keys.ControlLeft && !p.fly);\n    const jump = !!(n.up || keys.Space || touchBtn.jump);\n    const down = !!(keys.KeyC || (p.fly && (keys.ShiftLeft || keys.ShiftRight)) || touchBtn.down || n.down);"),
    ("  const keys = Object.create(null);",
     "  const keys = Object.create(null);\n  let consoleInput = {};   /* My World 71: the console's Walk in (as in Santorini) */\n"
     "  const consoleControls = {\n    input: function (next) { consoleInput = Object.assign({}, next); },\n"
     "    stop: function () { consoleInput = {}; for (const k in keys) keys[k] = false; joy.x = joy.y = 0; touchBtn.jump = touchBtn.down = false; player.vel.set(0, 0, 0); }\n  };"),
    ("  function updateCamera(dt) {", "  function updateCamera(dt) {\n    if (window.MinestOiaEditor && window.MinestOiaEditor.frame()) return;   /* My World 71: the editing camera */"),
    ("const t = ((S.time % 24) + 24) % 24;", "const t = window.MinestOiaEditor && window.MinestOiaEditor.active && window.MinestOiaEditor.daylight ? 12 : ((S.time % 24) + 24) % 24;"),
]
for wid, page, app, glob, name in WORLDS:
    p = ROOT / app; s = p.read_text(encoding='utf-8')
    if 'My World 71' not in s:
        for a, b in MOVE:
            assert s.count(a) == 1, (app, a[:50])
            s = s.replace(a, b)
        a = 'window.' + glob + ' = {'
        assert s.count(a) == 1, (app, a)
        s = s.replace(a, 'window.' + glob + ' = window.__voxel = { controls: consoleControls,')
        p.write_text(s, encoding='utf-8')
    s = p.read_text(encoding='utf-8')
    if '/* 71 clouds */' not in s:   # as in Santorini: no cloud layer between the editing camera and the world
        a = '    // clouds\n    const TILE = cloudMesh.userData.TILE'
        assert s.count(a) == 1, (app, 'clouds')
        s = s.replace(a, '    cloudMesh.visible = !(window.MinestOiaEditor && window.MinestOiaEditor.active);   /* 71 clouds */\n' + a)
        p.write_text(s, encoding='utf-8')
    hp = ROOT / page; h = hp.read_text(encoding='utf-8')
    up = '../' * page.count('/')
    h = re.sub(r'<link rel="stylesheet" href="[./]*ui/voxel-shell\.css[^"]*" data-shell="71">\n', '', h)
    h = re.sub(r'<script src="[./]*ui/voxel-shell\.js[^"]*"[^>]*data-shell="71"></script>\n', '', h)
    h = h.replace('</head>', '<link rel="stylesheet" href="' + up + 'ui/voxel-shell.css?v=71" data-shell="71">\n</head>', 1)
    i = h.rindex('</body>')
    h = h[:i] + '<script src="' + up + 'ui/voxel-shell.js?v=71" data-world="' + wid + '" data-name="' + name + '" data-shell="71"></script>\n' + h[i:]
    hp.write_text(h, encoding='utf-8')
    print('shell', wid)

for page, kind, wid, name, title in PROXY:
    hp = ROOT / page; h = hp.read_text(encoding='utf-8'); up = '../' * page.count('/')
    h = re.sub(r'<link rel="stylesheet" href="[./]*ui/voxel-shell\.css[^"]*" data-shell="71">\n', '', h)
    h = re.sub(r'<script src="[./]*ui/voxel-shell-lite\.js[^"]*"[^>]*data-shell="71"></script>\n', '', h)
    h = h.replace('</head>', '<link rel="stylesheet" href="' + up + 'ui/voxel-shell.css?v=71" data-shell="71">\n</head>', 1)
    i = h.rindex('</body>')
    h = h[:i] + '<script src="' + up + 'ui/voxel-shell-lite.js?v=71" data-kind="' + kind + '" data-world="' + wid + '" data-name="' + name + '" data-title="' + title + '" data-shell="71"></script>\n' + h[i:]
    hp.write_text(h, encoding='utf-8')
    print('shell (own engine)', wid)

# ---- 3. My World: open them in the shell
PARENT = (SRC / 'parent.js').read_text(encoding='utf-8')
assert '</script' not in PARENT.lower()
for f in MY_WORLD:
    p = ROOT / f
    if not p.exists():
        continue
    s = p.read_text(encoding='utf-8')
    if 'function openWorldOverlay3D' not in s:
        continue
    s = re.sub(r'<script id="mn-world-shell-71">.*?</script>\n', '', s, flags=re.S)
    i = s.rindex('</body>')
    s = s[:i] + '<script id="mn-world-shell-71">\n' + PARENT + '</script>\n' + s[i:]
    p.write_text(s, encoding='utf-8')
    print('my world', f)

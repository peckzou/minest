const {chooseView}=require('./view-switcher.cjs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');
const path = require('node:path');
const outputRoot = process.env.MINEST_TEST_OUTPUT || path.resolve(__dirname,'..');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const page = await browser.newPage({ viewport:{width:1440,height:900} });
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  const fixture = fs.existsSync(path.join(outputRoot,'sample-board.json')) ? path.join(outputRoot,'sample-board.json') : path.resolve(__dirname,'../../../ec6_anchor_charts_143_board.json');
  const board = JSON.parse(fs.readFileSync(fixture));
  board.id = 'image-v1-test'; board.title = 'Image Views · 200 cards';
  let all = board.columns.flatMap(c=>c.cards).map((c,i)=>{
    c=JSON.parse(JSON.stringify(c)); c.id='image-'+i; c.title=String(i).padStart(3,'0')+' · '+c.title;
    c.complete=i%3===0;c.priority=['high','medium','low'][i%3];c.labels=[i%2?'odd':'even'];
    function local(v){return typeof v==='string'?v.replace('https://minest-app.vercel.app',''):v;}
    c.image=local(c.image);c.cover.value=local(c.cover.value);c.cover.fullUrl=c.cover.value.replace('/thumbs/','/full/');
    return c;
  });
  for(let i=all.length;i<200;i++){let c=structuredClone(all[i%143]);c.id='image-'+i;c.title=String(i).padStart(3,'0')+' · More';all.push(c);}
  board.columns=[{id:'list-a',title:'Anchor charts',color:'#5597ff',cards:all.slice(0,100)},{id:'list-b',title:'Second list',color:'#ec7a92',cards:all.slice(100)}];
  const serialized=JSON.stringify(board);
  await page.addInitScript(({serialized})=>{
    localStorage.setItem('focusboard_boards_v7_2',JSON.stringify([JSON.parse(serialized)]));
    localStorage.setItem('focusboard_active_id_v7_2','image-v1-test');
    localStorage.setItem('focusboard_theme_mode_v7','white');
  },{serialized});
  await page.route('**/*', route => {
    const url=route.request().url();
    if(url.startsWith('http://127.0.0.1:8765') || url.startsWith('data:') || url.startsWith('blob:')) return route.continue();
    return route.abort();
  });
  const start=Date.now();
  await page.goto((process.env.MINEST_ENTRY_URL || 'http://127.0.0.1:8765/')+'?mode=photos',{waitUntil:'domcontentloaded'});
  await page.waitForSelector('.miv-tile',{timeout:30000});
  console.log('LOAD',Date.now()-start,'ms', 'tiles', await page.locator('.miv-tile').count());
  console.log('ERRORS',errors);
  console.log('IMAGES',await page.locator('.miv-tile img').evaluateAll(imgs=>({total:imgs.length,loaded:imgs.filter(x=>x.complete&&x.naturalWidth).length})));
  await page.screenshot({path:path.join(outputRoot,'mac-photos.png')});
  await page.locator('[data-card-id="image-80"].miv-tile').click();
  await page.waitForSelector('.miv-viewer'); await page.keyboard.press('Escape');
  console.log('SELECT',await page.evaluate(()=>MinestImageViews.state('image-v1-test').selected));
  const scrollBefore = await page.locator('.miv-scroll').evaluate(e=>e.scrollTop);
  await chooseView(page,'pins');
  await page.waitForSelector('.miv-pins');
  await page.waitForTimeout(350);
  await page.screenshot({path:path.join(outputRoot,'mac-pins.png')});
  assert.equal(await page.locator('.miv-selected').getAttribute('data-card-id'),'image-80');
  console.log('PINS',await page.locator('.miv-selected').getAttribute('data-card-id'));
  await chooseView(page,'coverflow');
  await page.waitForSelector('.coverflow-card-item');
  await page.waitForTimeout(400);
  console.log('CF',await page.evaluate(()=>({selected:MinestImageViews.state('image-v1-test').selected,visible:[...document.querySelectorAll('.coverflow-card-item')].map(e=>e.dataset.cardId)})));
  assert.equal(await page.evaluate(()=>MinestImageViews.state('image-v1-test').selected),'image-80');
  assert.ok(await page.locator('.coverflow-card-item').count() <= 9);
  await page.screenshot({path:path.join(outputRoot,'mac-coverflow.png')});
  await page.locator('.miv-cf-open').click();
  await page.waitForSelector('.miv-viewer');
  const cfViewer = await page.locator('.miv-viewer').boundingBox();
  assert.equal(cfViewer.width,1440); assert.equal(cfViewer.height,900);
  await page.keyboard.press('Escape');
  await chooseView(page,'photos');
  await page.waitForSelector('.miv-photos');
  console.log('BACK',await page.evaluate(()=>MinestImageViews.state('image-v1-test').selected));
  await page.waitForTimeout(350);
  const scrollAfter = await page.locator('.miv-scroll').evaluate(e=>e.scrollTop);
  console.log('SCROLL', {before:scrollBefore,after:scrollAfter});
  assert.ok(Math.abs(scrollBefore-scrollAfter)<3, 'Photos restores its scroll offset');
  await page.locator('[data-card-id="image-80"].miv-tile').click();
  await page.waitForSelector('.miv-viewer');
  console.log('VIEWER',await page.locator('.miv-viewer-pan img').getAttribute('src'));
  await page.waitForFunction(()=>document.querySelector('.miv-viewer-pan img').naturalWidth>=1500);
  await page.getByRole('button',{name:'Zoom photo',exact:true}).click();
  assert.ok(await page.getByRole('button',{name:'Fit photo',exact:true}).isVisible());
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('Escape');
  console.log('NEXT',await page.evaluate(()=>MinestImageViews.state('image-v1-test').selected));
  await page.setViewportSize({width:390,height:844});
  await chooseView(page,'pins');
  await page.waitForTimeout(600);
  const visibleSelection = await page.locator('.miv-selected').evaluate(el=>{const r=el.getBoundingClientRect();return r.bottom>120&&r.top<innerHeight;});
  assert.ok(visibleSelection,'Selected image remains in view after thumbnail layout settles');
  await page.screenshot({path:path.join(outputRoot,'iphone-pins.png')});
  console.log('PHONE',await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,grid:document.querySelector('.miv-pins').getBoundingClientRect().width})));

  await page.evaluate(()=>MinestAI.selectList('list-b'));
  await page.waitForFunction(()=>document.querySelectorAll('.miv-tile').length===100);
  assert.equal(await page.locator('.miv-tile').count(),100);
  await page.evaluate(()=>MinestAI.selectList('missing'));
  await page.waitForSelector('.miv-empty');
  assert.equal(await page.evaluate(()=>MinestImageViews.state('image-v1-test').selected),null);
  await page.evaluate(()=>MinestAI.selectList('all'));
  await page.waitForSelector('.miv-tile');
  await chooseView(page,'photos');
  await chooseView(page,'coverflow');
  await chooseView(page,'pins');
  await page.waitForTimeout(450);
  assert.equal(await page.locator('[data-miv-flight]').count(),0);
  await page.emulateMedia({reducedMotion:'reduce'});
  await chooseView(page,'coverflow');
  assert.equal(await page.locator('[data-miv-flight]').count(),0);
  await chooseView(page,'photos');
  await page.setViewportSize({width:951,height:669});
  await page.goto((process.env.MINEST_DUO_URL || 'http://127.0.0.1:8765/Minest-Image-Views-Duo-V1.html')+'?mode=photos',{waitUntil:'domcontentloaded'});
  await page.waitForSelector('.miv-tile');
  await page.evaluate(()=>{document.documentElement.classList.add('duo-cover'); SpatialFold.dual(true);});
  await page.waitForSelector('.coverflow-card-item');
  await page.locator('.miv-tile[data-card-id="image-25"]').click();
  await page.waitForSelector('.miv-viewer'); await page.keyboard.press('Escape');
  await page.waitForTimeout(400);
  const duo = await page.evaluate(()=>({selected:MinestImageViews.state('image-v1-test').selected,panes:[document.querySelector('.miv-pane'),document.querySelector('[data-sf-view="coverflow"]')].map(e=>({w:e.clientWidth,h:e.clientHeight})),width:document.documentElement.scrollWidth}));
  assert.equal(duo.selected,'image-25');
  assert.ok(duo.panes.every(p=>p.w>200&&p.h>200));
  assert.ok(duo.width<=951);
  console.log('DUO',duo);
  await page.screenshot({path:path.join(outputRoot,'duo-photos-coverflow.png')});
  await page.setViewportSize({width:669,height:951});
  await page.waitForTimeout(500);
  const portrait = await page.evaluate(()=>[document.querySelector('.miv-pane'),document.querySelector('[data-sf-view="coverflow"]')].map(e=>({w:e.clientWidth,h:e.clientHeight})));
  console.log('DUO PORTRAIT',portrait);
  assert.ok(portrait.every(p=>p.h>250 && p.h<600));
  await page.screenshot({path:path.join(outputRoot,'duo-portrait.png')});
  await page.locator('.miv-cf-open').click();
  const duoViewer = await page.locator('.miv-viewer').boundingBox();
  assert.equal(duoViewer.width,669); assert.equal(duoViewer.height,951);
  await page.keyboard.press('Escape');
  if (!process.env.MINEST_ENTRY_URL) {
  const demo = await browser.newPage({viewport:{width:1440,height:900}});
  await demo.route('**/*',r=>r.request().url().startsWith('http://127.0.0.1:8765')?r.continue():r.abort());
  await demo.goto('http://127.0.0.1:8765/Minest-Image-Views-Demo-V1.html?mode=photos',{waitUntil:'domcontentloaded'});
  await demo.waitForSelector('.miv-tile');
  assert.equal(await demo.locator('.miv-tile').count(),143);
  await demo.close();
  }
  assert.deepEqual(errors,[]);
  console.log('PASS: browser integration, list/empty state, rapid switching, reduced motion, HD viewer, phone and Duo.');
  console.log('FINAL ERRORS',errors);

  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
